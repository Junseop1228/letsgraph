// Generates styles/tokens.css from DESIGN.md (YAML front matter = light values) + design/dark.json.
// Usage: npm run tokens   (edit DESIGN.md, run this, the dev server hot-reloads)
// Source of truth: ../DESIGN.md (project root) when present, copied to design/DESIGN.md so the app repo is self-contained.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const projectDesign = resolve(root, "..", "DESIGN.md");
const localDesign = resolve(root, "design", "DESIGN.md");
if (existsSync(projectDesign)) copyFileSync(projectDesign, localDesign);

const md = readFileSync(localDesign, "utf8");
const fm = md.split(/\r?\n---\r?\n/)[0].replace(/^---\r?\n/, "");
const ds = parse(fm);
const dark = JSON.parse(readFileSync(resolve(root, "design", "dark.json"), "utf8"));

const light = ds.colors;
const names = Object.keys(light);
for (const n of names) if (!(n in dark)) throw new Error(`design/dark.json is missing "${n}"`);

const L = [];
L.push("/* GENERATED by scripts/design-tokens.mjs from DESIGN.md + design/dark.json. Do not edit by hand. */");
L.push(":root {");
for (const n of names) L.push(`  --ds-${n}: ${light[n]};`);
L.push("  --ds-on-error: #ffffff;");
for (const [k, v] of Object.entries(ds.rounded)) L.push(`  --ds-radius-${k}: ${v};`);
L.push("  color-scheme: light;");
L.push("}");
L.push(".dark {");
for (const n of names) L.push(`  --ds-${n}: ${dark[n]};`);
L.push("  color-scheme: dark;");
L.push("}");
L.push("");
L.push("@theme inline {");
L.push("  /* our tokens, 1:1 with DESIGN.md: bg-bg-sunken, text-text-secondary, border-border-emphasized ... */");
for (const n of names) L.push(`  --color-${n}: var(--ds-${n});`);
L.push("  /* shadcn/ui public layer (DESIGN.md > Components table) */");
const alias = {
  background: "bg-page", foreground: "text-primary",
  card: "bg-surface", "card-foreground": "text-primary",
  popover: "bg-surface", "popover-foreground": "text-primary",
  "primary-foreground": "on-accent",
  secondary: "bg-tonal", "secondary-foreground": "text-primary",
  muted: "bg-sunken", "muted-foreground": "text-secondary",
  "accent-foreground": "text-primary",
  destructive: "error", input: "border-emphasized", ring: "accent",
  "chart-1": "data-1", "chart-2": "data-2", "chart-3": "data-3",
};
for (const [k, v] of Object.entries(alias)) L.push(`  --color-${k}: var(--ds-${v});`);
// shadcn 'accent' is a hover fill; ours is the ink action colour -> keep ours as --color-accent, expose shadcn's as bg-accent-soft
L.push("  --color-accent-soft: var(--ds-bg-tonal-hover);");
L.push("  --color-destructive-foreground: var(--ds-on-error);");
L.push("  /* radius: shadcn sm/md/lg/xl -> inner/element/container */");
for (const k of Object.keys(ds.rounded)) L.push(`  --radius-${k}: var(--ds-radius-${k});`);
L.push("  --radius-sm: var(--ds-radius-inner);");
L.push("  --radius-md: var(--ds-radius-element);");
L.push("  --radius-lg: var(--ds-radius-container);");
L.push("  --radius-xl: var(--ds-radius-container);");
L.push("  /* type roles -> text-body, text-heading-1, text-figure ... (size + line-height + tracking + weight) */");
for (const [k, t] of Object.entries(ds.typography)) {
  L.push(`  --text-${k}: ${t.fontSize};`);
  L.push(`  --text-${k}--line-height: ${t.lineHeight};`);
  if (t.letterSpacing) L.push(`  --text-${k}--letter-spacing: ${t.letterSpacing};`);
  if (t.fontWeight) L.push(`  --text-${k}--font-weight: ${t.fontWeight};`);
}
L.push("  /* spacing tokens -> h-control-md, w-drawer-width ... */");
for (const [k, v] of Object.entries(ds.spacing)) L.push(`  --spacing-${k}: ${v};`);
L.push("}");
writeFileSync(resolve(root, "styles", "tokens.css"), L.join("\n") + "\n", "utf8");
console.log(`tokens.css: ${names.length} colours, ${Object.keys(ds.typography).length} type roles, ${Object.keys(ds.rounded).length} radii, ${Object.keys(ds.spacing).length} spacing`);
