// Licence inventory for NFR-EXT-03: lists every production dependency (from package-lock.json) with its licence,
// flags anything outside the allowed set, and appends the full text of licences that must travel with
// shipped files (Pretendard OFL-1.1, bundled as a web font). Usage: npm run licenses -> THIRD_PARTY_NOTICES.md
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8"));
const ALLOWED = /^(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|OFL-1\.1|CC0-1\.0|BlueOak-1\.0\.0|Python-2\.0|CC-BY-4\.0)$/;

const rows = [];
for (const [path, meta] of Object.entries(lock.packages ?? {})) {
  if (!path || meta.dev || meta.devOptional) continue;
  const name = path.replace(/^.*node_modules\//, "");
  let license = meta.license;
  if (!license) {
    const pj = resolve(root, path, "package.json");
    if (existsSync(pj)) license = JSON.parse(readFileSync(pj, "utf8")).license;
  }
  license = typeof license === "string" ? license : license?.type ?? "UNKNOWN";
  const parts = license.replace(/[()]/g, "").split(/\s+(?:OR|AND)\s+/);
  const ok = parts.some((p) => ALLOWED.test(p.trim())) && !/AGPL|GPL-[23]|SSPL|BUSL|Commons-Clause/i.test(license);
  rows.push({ name, version: meta.version ?? "", license, ok });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const flagged = rows.filter((r) => !r.ok);

const out = [
  "# Third-party notices",
  "",
  "Generated by `npm run licenses` from package-lock.json (production dependencies only). Allowed licences follow NFR-EXT-03 (MIT, Apache-2.0, BSD, ISC; OFL for fonts; no AGPL for networked parts).",
  "",
  `Packages: ${rows.length} · needs review: ${flagged.length}`,
  "",
  ...(flagged.length ? ["## Needs review", "", ...flagged.map((r) => `- ${r.name}@${r.version}: ${r.license}`), ""] : []),
  "## Packages",
  "",
  "| Package | Version | Licence |",
  "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
  "## Pretendard (SIL Open Font License 1.1)",
  "",
  "The web font file is shipped with the app (next/font/local from the `pretendard` package).",
  "",
  "```",
  readFileSync(resolve(root, "design/fonts/Pretendard-OFL.txt"), "utf8").trim(),
  "```",
  "",
];
writeFileSync(resolve(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"), "utf8");
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages, ${flagged.length} need review`);
for (const r of flagged) console.log(`  REVIEW ${r.name}@${r.version}: ${r.license}`);
